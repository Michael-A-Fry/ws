"""Keep the code map in AGENTS.md generated from the module docstrings, so it cannot drift from the code.

usage: gen_code_map.py            rewrite the map between the markers in AGENTS.md
       gen_code_map.py --check    exit 1 if AGENTS.md is not current (what prek and CI run)

One row per module in src/ws, and one per sub-package (read from its __init__.py). Each row is the first sentence of the
module docstring, read with `ast`, so nothing is imported or run. Stdlib only.
"""

from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "src" / "ws"
TARGET = ROOT / "AGENTS.md"
START = "<!-- code-map:start (generated by scripts/gen_code_map.py; edit the module docstring, not this table) -->"
END = "<!-- code-map:end -->"
_SKIP = {"__init__.py", "__main__.py"}
_MAX = 100


def first_sentence(doc: str) -> str:
    text = " ".join(doc.split())
    cut = re.search(r"\.(\s|$)", text)
    if cut:
        text = text[: cut.start()]
    if len(text) > _MAX:
        text = text[: _MAX - 3].rsplit(" ", 1)[0].rstrip(",;:") + "..."
    return text.replace("|", "\\|")


def docstring(path: Path) -> str:
    try:
        tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    except SyntaxError:
        return "(does not parse)"
    return first_sentence(ast.get_docstring(tree) or "") or "(no docstring)"


def rows() -> list[tuple[str, str]]:
    found = [(f"`{p.name}`", docstring(p)) for p in PKG.glob("*.py") if p.name not in _SKIP]
    found += [(f"`{p.name}/`", docstring(p / "__init__.py")) for p in PKG.iterdir() if (p / "__init__.py").is_file()]
    return sorted(found, key=lambda r: (r[0].strip("`").rstrip("/"), r[0]))


def render() -> str:
    lines = [START, "", "| Where (under `src/ws/`) | What it is |", "|---|---|"]
    lines += [f"| {where} | {what} |" for where, what in rows()]
    return "\n".join([*lines, "", END])


def updated(current: str) -> str:
    start, end = current.find(START.split(" (")[0]), current.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"gen_code_map: AGENTS.md needs the markers {START!r} ... {END!r}")
    return current[:start] + render() + current[end + len(END) :]


def main(argv: list[str]) -> int:
    if not TARGET.is_file():
        print("gen_code_map: AGENTS.md is missing", file=sys.stderr)
        return 1
    current = TARGET.read_text(encoding="utf-8")
    new = updated(current)
    if "--check" in argv:
        if new != current:
            print(
                "AGENTS.md code map is out of date: run `python3 scripts/gen_code_map.py` and commit it",
                file=sys.stderr,
            )
            return 1
        return 0
    if new != current:
        TARGET.write_text(new, encoding="utf-8")
        print("gen_code_map: updated the code map in AGENTS.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
