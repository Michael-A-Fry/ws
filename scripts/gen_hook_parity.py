"""Keep docs/reference/hook-parity.md generated from docs/reference/hook-parity.toml, so the page and the tests read one table.

usage: gen_hook_parity.py            rewrite the page
       gen_hook_parity.py --check    exit 1 if the page is not current (what prek and CI run)

`load()` returns the rows, `render()` the page, and `missing(names)` the names in an inventory that no row has (a test
plants a dummy name to prove it goes red). Stdlib only.
"""

from __future__ import annotations

import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "docs" / "reference" / "hook-parity.toml"
PAGE = ROOT / "docs" / "reference" / "hook-parity.md"
STATUSES = ("covered", "planned", "estate", "dropped")
FAILS = ("blocks", "never-blocks")
FIELDS = {"id", "what", "ws", "status", "fail", "test", "wave"}

HEAD = """<!-- GENERATED by scripts/gen_hook_parity.py from docs/reference/hook-parity.toml: DO NOT EDIT; edit the .toml and run the script -->
# What a hand-built hook set does, and where ws does it

People who've wired their own hooks into Claude Code or OpenCode usually end up with the same kinds of hook: a shell
guard, a secrets guard, a protected-files guard, a staging guard, a claims check, an alert. This page maps each kind to
the ws rule or guard that does the same job, and says what happens when that check crashes. It's for anyone moving a
hand-built set to ws, and for anyone who wants to know what ws covers without reading the code.

Each row is one class of hook (a user-level hook that ...). The status says where its job lives now:

- **covered**: a ws rule or guard does it. The last column names the test that sends the same sample call to the ws
  side and checks the decision.
- **planned**: ws will do it; the row names the wave. No row may stay planned at release.
- **estate**: the job belongs to one person's own setup (their dashboards, their folder layout, their queue), so it
  lives in that person's private config and not in ws. ws gives the place to hang it (a `deny_commands` pattern, a
  guard, a hook of your own), and the reason is in the row.
- **dropped**: ws has no counterpart, and the reason says why.

The *If it crashes* column is the fail mode: **blocks** means a crash or a doubt denies the call (the gate fails
closed); **never-blocks** means the hook only advises or records, so a crash is one stderr line.

All of ws's hooks reach the runner through one command, the [resident gate](gate.md#the-resident-gate), so each
covered row runs in the same fixed order: the policy's rules first, then the guards that are on, lowest priority first
(see [guards](guards.md#the-order-guards-run-in)).

"""

TAIL = """
The ws guards with no row above are ones nobody asked for in a hand-built set: `dev-server` (stops a second dev server
starting), `checkout-pin` (keeps work in worktrees) and `record-calls` (records calls for [replay](gate.md)). They're
off or on in `[guards] on`, like the rest.

## Swapping the hook layer for another runner's

The table doesn't change when the runner does. One adapter module owns the translation: `src/ws/adapters/claude_code.py`
or `src/ws/adapters/opencode.py` turns the policy into that runner's own config and parses that runner's hook payload
into a neutral call, and `ws gate` judges the call. To move to a third runner, add a module to `src/ws/adapters/` (the
contract is in that folder's docstring) and list in its `CANNOT_CHECK` every check it can't enforce; `ws run` then
refuses a job whose policy needs one, so a gap is a refusal and never a silent allow.

## How the rows are kept true

`tests/test_hook_parity.py` reads `docs/reference/hook-parity.toml`. A `covered` row must name a test in that file, and
each test sends one sample call that a hand-built hook would stop (and one it would let through) to the ws side. The
tests fail if a row has no test or a bad status or fail mode, if a hook in an inventory has no row, if a test has no
row, or if this page isn't what the script writes from the table.

A row can move from `estate` or `dropped` to `covered` when ws grows the rule. Moving the other way needs a reason in
the row.
"""


def load(path: Path = DATA) -> list[dict]:
    rows = tomllib.loads(path.read_text(encoding="utf-8")).get("hook", [])
    for r in rows:
        extra = set(r) - FIELDS
        if extra or not {"id", "what", "ws", "status", "fail", "test"} <= set(r):
            raise ValueError(f"hook row {r.get('id')!r}: bad keys {sorted(extra)} or a missing one")
    return rows


def render(rows: list[dict] | None = None) -> str:
    rows = load() if rows is None else rows
    lines = [
        "| # | Class | What the hook does | In ws | Status | If it crashes | Test |",
        "|---|---|---|---|---|---|---|",
    ]
    for n, r in enumerate(rows, 1):
        status = r["status"] + (f" (wave {r['wave']})" if r["status"] == "planned" else "")
        test = f"`{r['test']}`" if r["test"] != "none" else "none"
        lines.append(f"| {n} | `{r['id']}` | {r['what']} | {r['ws']} | {status} | {r['fail']} | {test} |")
    return HEAD + "\n".join(lines) + "\n" + TAIL


def missing(names, rows: list[dict] | None = None) -> list[str]:
    """The names in an inventory that no row has."""
    have = {r["id"] for r in (load() if rows is None else rows)}
    return sorted(set(names) - have)


def main(argv: list[str]) -> int:
    text = render()
    if argv == ["--check"]:
        if PAGE.read_text(encoding="utf-8") != text:
            print("docs/reference/hook-parity.md is not current: run python3 scripts/gen_hook_parity.py")
            return 1
        return 0
    PAGE.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
