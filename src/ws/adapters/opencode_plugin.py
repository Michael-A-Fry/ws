"""The OpenCode shim plugin, as the JavaScript text `ws gate generate` writes to plugins/ws-gate.js.

Kept as a Python string, not a .js file, because the secret wall copies the ws package as plain .py files only.
`/*__CHECK__*/ []` is replaced with the argv of the thin gate client (ws.gateclient), which asks the resident gate and runs
`ws gate check` itself when it can't answer, so OpenCode and Claude Code get the same decision; `/*__EVENT__*/ []` with the
same client's argv for `ws gate event` (the guards on OpenCode's other events); `/*__WS__*/ []` with the argv that runs ws;
`/*__PIN__*/ []` with the `--pin` arguments that go on the commands that are not a check (the layout ws install resolved).
`/*__GOVERNED__*/ []` and `/*__POST_TOOLS__*/ []` name the tools a call is checked before and after, `/*__ADVICE__*/ []` the
ws events (start, prompt, post, stop, subagent-stop) a guard that is on wants, `/*__ASK__*/ []` the `ask_commands` patterns
written as OpenCode's own `ask`, `/*__ASKS__*/ ""` the file its permission asks are appended to (ws home reads it) and
`/*__ASKS_SCHEMA__*/ 0` the `schema` number of each line in it.
"""

SOURCE = r"""// ws gate shim for OpenCode. Generated by `ws gate generate`; edit policy.toml, not this file.
// Asks `ws gate check` about each shell, read, search, edit and web call before it runs and throws on a deny. The guards
// that are on (ws.guards) run on OpenCode's other events through the same thin client: after a call, when a session
// starts, on a prompt, and when a session goes idle. Only the check before a call can block.
// Fails closed: if ws cannot be run, or says anything but "allow", the call is blocked. The session id and folder go
// with the call so an approval (`ws approve`) can be bound to them. They come from OpenCode's own hook input, never
// from the tool's arguments, which only ever sit under `args` and `tool_input`.
import { spawn, spawnSync } from "node:child_process"
import { randomUUID } from "node:crypto"
import { appendFileSync, mkdirSync, readSync, renameSync, statSync, writeSync } from "node:fs"
import { dirname, resolve } from "node:path"

const CHECK = /*__CHECK__*/ []
const EVENT = /*__EVENT__*/ []
const WS = /*__WS__*/ []
const PIN = /*__PIN__*/ []
const GOVERNED = /*__GOVERNED__*/ []
const POST_TOOLS = /*__POST_TOOLS__*/ []
const ADVICE = /*__ADVICE__*/ []
const ASK = /*__ASK__*/ []
const ASKS = /*__ASKS__*/ ""
const ASKS_SCHEMA = /*__ASKS_SCHEMA__*/ 0 // the `schema` of each line in the asks file (docs/reference/stores.md)
const ASKS_MAX = 8 * 1024 * 1024 // bytes: past this the asks file moves to `.old`, well under the 64 MiB ws home refuses
const ADVICE_MS = 10000 // ms: the longest an advice event may hold OpenCode up; the check keeps its own, longer bound
const governed = new Set(GOVERNED)

// Session notes (advice, never a gate): record the release on session.created; on session.idle ask `ws session nudge`
// and show its one line as a toast. Checked against OpenCode 1.19.4 in a real run (tests/e2e/test_opencode_nudge.py):
// both events fire.
const sessionId = (e) => e.properties?.info?.id ?? e.properties?.sessionID
const ws = (sub, id) =>
  spawnSync(WS[0], [...WS.slice(1), "session", sub, "--runner", "opencode", "--session-id", id, ...PIN], {
    encoding: "utf8",
    timeout: 3000,
    stdio: ["ignore", "pipe", "ignore"],
  })

// The guards on OpenCode's other events: `ws gate event` through the thin client, with a short bound. The answer is
// {code, out, err}, or null when there is nothing to run, it could not start or it took too long. Advice is never a
// reason to stop the session, so every failure ends here as a null.
const advice = (event, body) =>
  new Promise((done) => {
    if (!EVENT.length || !ADVICE.includes(event)) return done(null)
    let out = ""
    let err = ""
    let over = false
    let timer
    const finish = (code) => {
      if (over) return
      over = true
      clearTimeout(timer)
      done(code === null ? null : { code, out, err })
    }
    try {
      const child = spawn(EVENT[0], EVENT.slice(1), { stdio: ["pipe", "pipe", "pipe"] })
      timer = setTimeout(() => {
        try {
          child.kill("SIGKILL")
        } catch {}
        finish(null)
      }, ADVICE_MS)
      child.stdout.on("data", (d) => (out = (out + d).slice(0, 20000)))
      child.stderr.on("data", (d) => (err = (err + d).slice(0, 20000)))
      child.on("error", () => finish(null))
      child.on("close", (code) => finish(code))
      child.stdin.on("error", () => {})
      child.stdin.end(JSON.stringify(body))
    } catch {
      finish(null)
    }
  })
// What a guard that reads the tool input sees: the tool's own arguments, and `run_in_background` for a task that runs
// in the background (OpenCode calls it `background`).
const toolInput = (a) => ({ ...(a ?? {}), ...(a?.background === true ? { run_in_background: true } : {}) })
// OpenCode's own wildcard: `*` is anything, `?` one character, and a trailing ` *` also matches the bare command.
const wild = (g) => {
  let s = g.replace(/[.+^${}()|[\]\\]/g, "\\$&").replace(/\*/g, ".*").replace(/\?/g, ".")
  if (s.endsWith(" .*")) s = s.slice(0, -3) + "( .*)?"
  return new RegExp("^" + s + "$", "s")
}
const ASK_RE = ASK.map(wild)

// A granted approval cannot be used up from inside the wall (its folder is read-only there). `ws gate check` then exits
// 4 and prints {"claim": ID}; the id goes down the socket the launcher left open (WS_APPROVAL_FD) and the launcher,
// outside the wall, uses the approval up and answers "ok" or "no <why>".
//
// The descriptor is marked close-on-exec as soon as the plugin loads, so the shell commands the model runs do not
// inherit it (OpenCode is a Bun program; fcntl comes from libc through bun:ffi; where that is not there the mark is
// not set and the descriptor stays open in children, which can then only waste an approval, never grant one).
const approvalFd = Number(process.env.WS_APPROVAL_FD)
const cloexec = async () => {
  if (!Number.isInteger(approvalFd) || approvalFd < 3) return
  try {
    const { dlopen, FFIType } = await import("bun:ffi")
    for (const lib of ["libc.so.6", "libc.dylib", "libSystem.B.dylib"]) {
      try {
        const { symbols } = dlopen(lib, { fcntl: { args: [FFIType.i32, FFIType.i32, FFIType.i32], returns: FFIType.i32 } })
        if (symbols.fcntl(approvalFd, 2, 1) === 0) return // F_SETFD, FD_CLOEXEC
      } catch {}
    }
  } catch {}
}
// Not readable or patchable by a process of the same user: /proc/PID/mem and ptrace of a dumpable process are allowed to
// any process of the same user when Yama's ptrace_scope is 0, which includes a shell command the model runs. prctl(
// PR_SET_DUMPABLE, 0) makes this process refuse both unless the caller has CAP_SYS_PTRACE, which the wall drops. It is not
// inherited by children (exec sets it again), so they stay ordinary processes. Where bun:ffi is not there nothing is set.
const undumpable = async () => {
  try {
    const { dlopen, FFIType } = await import("bun:ffi")
    const t = FFIType
    for (const lib of ["libc.so.6", "libc.dylib", "libSystem.B.dylib"]) {
      try {
        const { symbols } = dlopen(lib, { prctl: { args: [t.i32, t.u64, t.u64, t.u64, t.u64], returns: t.i32 } })
        if (symbols.prctl(4, 0, 0, 0, 0) === 0) return // PR_SET_DUMPABLE
      } catch {}
    }
  } catch {}
}
const claim = (id) => {
  const fd = approvalFd
  if (!Number.isInteger(fd) || fd < 3) return "no approval channel: start OpenCode with `ws gate launch`"
  const nonce = randomUUID()
  writeSync(fd, `claim ${id} ${nonce}\n`)
  const buf = Buffer.alloc(512)
  let out = ""
  while (!out.includes("\n")) {
    const n = readSync(fd, buf, 0, buf.length, null)
    if (n <= 0) break
    out += buf.toString("utf8", 0, n)
  }
  out = out.trim()
  if (out === `ok ${nonce}`) return "ok"
  return out.startsWith(`no ${nonce} `) ? out.slice(`no ${nonce} `.length) : out || "no answer"
}

export const WsGate = async ({ client, directory } = {}) => {
  await cloexec()
  await undumpable()
  const kids = new Set() // child sessions (a subagent's): they stop as a subagent and have no start or prompt of their own
  const dirs = new Map() // session id -> its folder, as OpenCode reported it when the session was created
  const startText = new Map() // session id -> a promise of the text the start guards printed
  const promptText = new Map() // session id -> the text the prompt guards printed for the turn in progress
  const sent = new Set() // sessions whose pending text went into the model's context
  const allowed = new Set() // call ids the gate let through, for an ask of ws's own to be answered (see asked)
  const folder = (id) => dirs.get(id) ?? directory ?? process.cwd()
  const body = (name, id) => ({ hook_event_name: name, session_id: id ?? "", cwd: folder(id) })
  const toast = async (message) => {
    try {
      await client?.tui?.showToast?.({ body: { message: message.slice(0, 600), variant: "info" } })
    } catch {}
  }
  // The runner's last message, for the guards that read what the model just said. Bounded like any advice.
  const lastMessage = async (id) => {
    const got = await Promise.race([
      client.session.messages({ path: { id } }),
      new Promise((_, no) => setTimeout(() => no(new Error("slow")), ADVICE_MS)),
    ])
    const list = Array.isArray(got?.data) ? got.data : []
    for (let i = list.length - 1; i >= 0; i--) {
      if (list[i]?.info?.role !== "assistant") continue
      return (list[i].parts ?? [])
        .filter((x) => x?.type === "text" && typeof x.text === "string")
        .map((x) => x.text)
        .join("\n")
    }
    return ""
  }
  // OpenCode's own `ask` rules, which ws writes for `ask_commands`, are the floor when this shim is not there. When it is,
  // the gate has already had its say, and a call the person approved with `ws approve` is let through: answering that ask
  // once, and only once, keeps the approved call from being asked a second time. OpenCode lists every shell segment of a
  // compound command in one ask (`ls && touch X` is `ls, touch X`), allowed or not, and does not say which of them
  // asked. A segment that is not one of ws's `ask_commands` might be the person's own `ask` rule, so the shim answers
  // only when every segment is one of ws's, on a call the gate allowed. Any other bash ask, and any ask that is not for
  // a shell command, is left to the person.
  const answer = async (p) => {
    try {
      if (typeof client?.permission?.reply === "function") {
        await client.permission.reply({ requestID: p.id, reply: "once" })
        return
      }
      await client.postSessionIdPermissionsPermissionId({
        path: { id: p.sessionID, permissionID: p.id },
        body: { response: "once" },
      })
    } catch {}
  }
  // The asks file ws home reads (JSON lines: an `added` line, then a closing one). Advice: a folder or file that cannot be
  // written (the wall keeps most of the disk read-only) is no reason to fail. A line starts with a newline, so one cut
  // short by a crash costs only itself (the reader skips a line that is not JSON), and the file moves to `.old` once it
  // passes ASKS_MAX, so it stays under what the reader accepts.
  const note = (line) => {
    if (!ASKS) return
    try {
      mkdirSync(dirname(ASKS), { recursive: true })
      try {
        if (statSync(ASKS).size > ASKS_MAX) renameSync(ASKS, ASKS + ".old")
      } catch {}
      appendFileSync(ASKS, "\n" + JSON.stringify({ schema: ASKS_SCHEMA, ...line, ts: Date.now() }) + "\n", { mode: 0o600 })
    } catch {}
  }
  const asked = async (p) => {
    const patterns = Array.isArray(p.patterns) ? p.patterns.map(String) : []
    const ours = p.permission === "bash" && patterns.length > 0 && patterns.every((x) => ASK_RE.some((re) => re.test(x)))
    note({
      event: "added",
      id: p.id,
      repo: folder(p.sessionID),
      session: { session_id: p.sessionID },
      question: `${p.permission}: ${patterns.join(", ")}`.slice(0, 300),
      options: [{ label: "Allow once" }, { label: "Reject" }],
      decision: "",
      source: "permission",
    })
    if (ours && p.tool?.callID && allowed.delete(p.tool.callID)) await answer(p) // after the line: the reply closes it
  }
  const closed = (p) => note({ event: "answered", id: p.requestID })
  const forget = (id) => {
    for (const m of [dirs, startText, promptText]) m.delete(id)
    kids.delete(id)
    sent.delete(id)
  }
  const idle = async (id) => {
    const line = (ws("nudge", id).stdout || "").trim()
    if (line) await toast(line)
    const child = kids.has(id)
    if (ADVICE.includes(child ? "subagent-stop" : "stop")) {
      const said = child ? {} : { last_assistant_message: await lastMessage(id).catch(() => "") }
      const r = await advice(child ? "subagent-stop" : "stop", {
        ...body(child ? "session.idle.child" : "session.idle", id),
        ...said,
      })
      if (r && r.err.trim()) await toast(r.err.trim())
    }
    // Text for the model that no request carried (the runner has no system transform): show it to the person instead.
    const pending = [startText.has(id) ? await startText.get(id) : "", promptText.get(id) ?? ""].filter(Boolean)
    if (pending.length && !sent.has(id)) await toast(pending.join("\n"))
    promptText.delete(id)
  }
  return {
    event: async ({ event }) => {
      try {
        const p = event.properties ?? {}
        if (event.type === "permission.asked") return await asked(p)
        if (event.type === "permission.replied") return closed(p)
        const id = sessionId(event)
        if (!id) return
        if (event.type === "session.deleted") return forget(id)
        if (event.type === "session.created") {
          if (event.properties?.info?.parentID) kids.add(id)
          if (typeof event.properties?.info?.directory === "string") dirs.set(id, event.properties.info.directory)
          ws("start", id)
          if (!kids.has(id)) {
            startText.set(
              id,
              advice("start", body("session.created", id)).then((r) => (r?.code === 0 ? r.out.trim() : "")),
            )
          }
        }
        if (event.type === "session.idle") await idle(id)
      } catch {}
    },
    // A prompt is sent: the guards that read it run, and what they print goes with the model's next request.
    "chat.message": async (input, output) => {
      try {
        const id = input.sessionID
        if (!id || kids.has(id) || !ADVICE.includes("prompt")) return
        promptText.delete(id)
        const text = (output.parts ?? [])
          .filter((x) => x?.type === "text" && !x.synthetic && typeof x.text === "string")
          .map((x) => x.text)
          .join("\n")
        const r = await advice("prompt", { ...body("chat.message", id), prompt: text })
        if (r?.code === 0 && r.out.trim()) promptText.set(id, r.out.trim())
      } catch {}
    },
    // Text from the start and prompt guards, added to the system prompt of each request the session makes. OpenCode
    // 1.19.4 has this hook (experimental.chat.system.transform); where it is missing the text goes to the toast on idle.
    "experimental.chat.system.transform": async (input, output) => {
      try {
        const id = input.sessionID
        if (!id) return
        const parts = [startText.has(id) ? await startText.get(id) : "", promptText.get(id) ?? ""].filter(Boolean)
        if (!parts.length) return
        output.system.push(parts.join("\n"))
        sent.add(id)
      } catch {}
    },
    "tool.execute.before": async (input, output) => {
      if (!governed.has(input.tool)) return
      const r = spawnSync(CHECK[0], CHECK.slice(1), {
        input: JSON.stringify({
          hook_event_name: "tool.execute.before",
          tool: input.tool,
          args: output.args ?? {},
          session_id: input.sessionID ?? "",
          cwd: resolve(directory ?? process.cwd(), output.args?.workdir ?? "."), // bash runs in args.workdir, if given
        }),
        encoding: "utf8",
        timeout: 30000, // ms: more than the client's worst case (ws.gateclient.WORST_CASE_S); a timed-out check is r.error, so blocked
      })
      if (r.status === 4 && !r.error) {
        let id = ""
        try {
          id = JSON.parse(r.stdout).claim
        } catch {}
        const answer = id ? claim(id) : "no claim id"
        if (answer !== "ok") throw new Error(`blocked by ws gate: ${answer.replace(/^no /, "")}`)
      } else if (r.error || r.status !== 0) {
        const why = (r.stderr || "").trim() || (r.error ? String(r.error.message) : `ws gate check exited ${r.status}`)
        throw new Error(`blocked by ws gate: ${why}`)
      }
      if (ASK.length && input.tool === "bash" && input.callID) {
        if (allowed.size > 500) allowed.clear()
        allowed.add(input.callID)
      }
    },
    // After a call: a deny or a warning from a guard goes to the model as more text on the tool's own output.
    "tool.execute.after": async (input, output) => {
      try {
        if (!POST_TOOLS.includes(input.tool)) return
        const r = await advice("post", {
          hook_event_name: "tool.execute.after",
          tool: input.tool,
          args: input.args ?? {},
          tool_input: toolInput(input.args),
          session_id: input.sessionID ?? "",
          cwd: resolve(directory ?? process.cwd(), input.tool === "bash" ? (input.args?.workdir ?? ".") : "."),
        })
        const text = r?.code === 2 ? r.err.trim() : ""
        if (text && typeof output.output === "string") output.output += "\n" + text
      } catch {}
    },
  }
}
"""
