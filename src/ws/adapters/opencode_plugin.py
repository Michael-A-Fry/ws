"""The OpenCode shim plugin, as the JavaScript text `ws gate generate` writes to plugins/ws-gate.js.

Kept as a Python string, not a .js file, because the secret wall copies the ws package as plain .py files only.
`/*__CHECK__*/ []` is replaced with the argv that runs `ws gate check`; `/*__WS__*/ []` with the argv that runs ws.
"""

SOURCE = r"""// ws gate shim for OpenCode. Generated by `ws gate generate`; edit policy.toml, not this file.
// Asks `ws gate check` about each shell, read, search, edit and web call before it runs and throws on a deny.
// Fails closed: if ws cannot be run, or says anything but "allow", the call is blocked.
import { spawnSync } from "node:child_process"

const CHECK = /*__CHECK__*/ []
const WS = /*__WS__*/ []
const GOVERNED = new Set(["bash", "read", "grep", "glob", "list", "edit", "write", "multiedit", "webfetch", "websearch"])

// Session notes (advice, never a gate): record the release on session.created; on session.idle ask `ws session nudge`
// and show its one line as a toast (OpenCode has no way for a plugin to add text to the model's context). Any error is
// swallowed. Unverified against OpenCode 1.19.4 in a real run: the event names come from the plugin docs.
const sessionId = (e) => e.properties?.info?.id ?? e.properties?.sessionID
const ws = (sub, id) =>
  spawnSync(WS[0], [...WS.slice(1), "session", sub, "--runner", "opencode", "--session-id", id], {
    encoding: "utf8",
    timeout: 3000,
    stdio: ["ignore", "pipe", "ignore"],
  })

export const WsGate = async ({ client } = {}) => ({
  event: async ({ event }) => {
    try {
      const id = sessionId(event)
      if (!id) return
      if (event.type === "session.created") ws("start", id)
      if (event.type === "session.idle") {
        const line = (ws("nudge", id).stdout || "").trim()
        if (line) await client?.tui?.showToast?.({ body: { message: line, variant: "info" } })
      }
    } catch {}
  },
  "tool.execute.before": async (input, output) => {
    if (!GOVERNED.has(input.tool)) return
    const r = spawnSync(CHECK[0], CHECK.slice(1), {
      input: JSON.stringify({ tool: input.tool, args: output.args ?? {} }),
      encoding: "utf8",
    })
    if (r.error || r.status !== 0) {
      const why = (r.stderr || "").trim() || (r.error ? String(r.error.message) : `ws gate check exited ${r.status}`)
      throw new Error(`blocked by ws gate: ${why}`)
    }
  },
})
"""
