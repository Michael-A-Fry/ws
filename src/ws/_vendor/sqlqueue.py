"""A persistent queue on one SQLite table, with fenced claims, idempotent submission and lease expiry. Stdlib only.

It is the one store engine under two ws features: the job queue (`ws.queue`) and, later, message delivery (claim at the
receiver's turn, `done` on acknowledgement, `retry_expired` for what was never acknowledged). Later users call this API
and do not edit this file.

    q = SqlQueue(path_or_connection, table="work", maxsize=None, timeout=30.0, clock=time.time_ns)

  * `target` is a file path (the queue opens its own connection: WAL, `synchronous=NORMAL`, autocommit mode, so every
    method runs its own `BEGIN IMMEDIATE`) or a `sqlite3.Connection` the caller owns, which must be in autocommit mode
    (`isolation_level=None`). With a caller's connection, a method called inside the caller's open transaction joins
    it, so a queue change and the caller's own rows commit or roll back together. `table` names the table, so one
    database can hold several queues and other tables; it is made on first use.
  * Times are integer Unix nanoseconds from `clock`. A test passes its own `clock`.

Messages (`Message`: `data` text, `message_id`, `status`, `in_time`, `ready_at`, `lock_time`, `done_time`,
`idempotency_key`, `claim_id`, `tries`). Status is `Status.READY` -> `LOCKED` -> `DONE` or `FAILED`.

    put(data, idempotency_key=None, ready_at=None, delay_s=0) -> Message
        Add a message. The same key with the same data returns the stored message (a replay changes nothing); the same
        key with other data raises `IdempotencyConflict`. A full queue (`maxsize` ready messages) raises `QueueFull`.
        `ready_at` (or `delay_s` from now) keeps it from being claimed before that time.
    pop() -> Message | None
        Claim the oldest ready message whose `ready_at` has come: it becomes LOCKED, `lock_time` is now and `claim_id`
        goes up by one. The claim id is the fence: only the holder of the current one can finish the claim.
    done(message_id, claim_id) / mark_failed(message_id, claim_id) -> Message
        Finish a claim as DONE or FAILED.
    retry(message_id, claim_id, delay_s=0, count_try=True) -> Message
        Put a claimed message back to READY, claimable again after `delay_s`; `count_try` adds one to `tries`.
    heartbeat(message_id, claim_id) -> Message
        Renew a claim's lease (`lock_time` is now).
        All four raise `StaleClaim` unless the message is LOCKED at exactly that claim id: a claim that was reclaimed
        after its lease expired, a message already finished, or a forged id all fail, and change nothing.
    retry_expired(lease_s, count_try=False) -> int
        Every LOCKED message whose lease (time since `lock_time`) is over `lease_s` seconds goes back to READY. Returns
        how many. A holder that comes back late then fails with `StaleClaim`.
    list_locked(older_than_s=None) -> list[Message]; list_ready(limit=None); get(message_id); qsize(); empty()
    discard(message_id) -> bool         delete a READY message (a cancel); False if it was not READY
    prune(older_than_s, statuses=(DONE, FAILED)) -> int
    close()

`store_error_kind(exc)` names a `sqlite3.Error` as `locked`, `full`, `readonly`, `unreadable` or `other` from SQLite's
own error code, never from the message text.
"""

from __future__ import annotations

import math
import re
import sqlite3
import threading
import time
import uuid
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from dataclasses import dataclass
from enum import IntEnum
from pathlib import Path

NS = 1_000_000_000
_TABLE = re.compile(r"^[a-z][a-z0-9_]{0,30}$")
_MODES = ("DEFERRED", "IMMEDIATE", "EXCLUSIVE")


class Status(IntEnum):
    READY = 0
    LOCKED = 1
    DONE = 2
    FAILED = 3


class QueueError(Exception):
    """Base of the queue's own errors; `kind` says which."""

    kind = "queue"


class IdempotencyConflict(QueueError, ValueError):
    """An idempotency key refers to a stored message with different data."""

    kind = "idempotency_conflict"


class StaleClaim(QueueError):
    """The claim id is not the message's current one, or the message is not locked: nothing was changed."""

    kind = "stale_claim"


class QueueFull(QueueError):
    """The queue already holds `maxsize` ready messages."""

    kind = "queue_full"


@dataclass(frozen=True, slots=True)
class Message:
    data: str
    message_id: str
    status: Status
    in_time: int
    ready_at: int
    lock_time: int | None
    done_time: int | None
    idempotency_key: str | None = None
    claim_id: int = 0
    tries: int = 0


def store_error_kind(exc: BaseException) -> str:
    """`locked`, `full`, `readonly`, `unreadable` or `other` for a sqlite3 error, by its error code (3.11 and later)."""
    code = getattr(exc, "sqlite_errorcode", None)
    if not isinstance(code, int):
        return "other"
    primary = code & 0xFF
    if primary in (5, 6):  # SQLITE_BUSY, SQLITE_LOCKED
        return "locked"
    if primary == 13:  # SQLITE_FULL
        return "full"
    if primary == 8:  # SQLITE_READONLY
        return "readonly"
    if primary in (10, 11, 14, 26):  # IOERR, CORRUPT, CANTOPEN, NOTADB
        return "unreadable"
    return "other"


def _row(r: sqlite3.Row) -> Message:
    return Message(
        data=r["data"],
        message_id=r["message_id"],
        status=Status(r["status"]),
        in_time=r["in_time"],
        ready_at=r["ready_at"],
        lock_time=r["lock_time"],
        done_time=r["done_time"],
        idempotency_key=r["idempotency_key"],
        claim_id=r["claim_id"],
        tries=r["tries"],
    )


def _seconds(value: float, name: str) -> int:
    if isinstance(value, bool) or not isinstance(value, (int, float)) or math.isnan(value) or value < 0:
        raise ValueError(f"{name} must be a number of seconds, zero or more")
    return int(min(value, 10**9) * NS)


class SqlQueue:
    def __init__(
        self,
        target: str | Path | sqlite3.Connection,
        *,
        table: str = "queue",
        maxsize: int | None = None,
        timeout: float = 30.0,
        clock: Callable[[], int] = time.time_ns,
    ) -> None:
        if not _TABLE.match(table):
            raise ValueError("table must be lower-case letters, digits and _, starting with a letter")
        if maxsize is not None and (isinstance(maxsize, bool) or not isinstance(maxsize, int) or maxsize < 0):
            raise ValueError("maxsize must be a whole number, zero or more, or None")
        self.table, self.maxsize, self.clock = table, maxsize, clock
        self._lock = threading.RLock()
        self._owns = not isinstance(target, sqlite3.Connection)
        if isinstance(target, sqlite3.Connection):
            if target.isolation_level is not None:
                raise ValueError("the connection must be in autocommit mode (isolation_level=None)")
            self.conn = target
            if target.row_factory is None:
                target.row_factory = sqlite3.Row
        else:
            self.conn = sqlite3.connect(str(target), isolation_level=None, timeout=timeout, check_same_thread=False)
            self.conn.row_factory = sqlite3.Row
            if str(self.conn.execute("PRAGMA journal_mode").fetchone()[0]).lower() != "wal":
                self.conn.execute("PRAGMA journal_mode = WAL")
            self.conn.execute("PRAGMA synchronous = NORMAL")
        t = self.table
        with self.transaction():
            self.conn.execute(
                f"""CREATE TABLE IF NOT EXISTS {t} (
                    message_id TEXT PRIMARY KEY,
                    data TEXT NOT NULL,
                    status INTEGER NOT NULL DEFAULT 0 CHECK (status IN (0, 1, 2, 3)),
                    in_time INTEGER NOT NULL,
                    ready_at INTEGER NOT NULL,
                    lock_time INTEGER,
                    done_time INTEGER,
                    idempotency_key TEXT,
                    claim_id INTEGER NOT NULL DEFAULT 0,
                    tries INTEGER NOT NULL DEFAULT 0
                )"""
            )
            self.conn.execute(
                f"CREATE UNIQUE INDEX IF NOT EXISTS {t}_key ON {t}(idempotency_key) WHERE idempotency_key IS NOT NULL"
            )
            self.conn.execute(f"CREATE INDEX IF NOT EXISTS {t}_ready ON {t}(status, ready_at)")

    # -- transactions -------------------------------------------------------------------------------------------

    @contextmanager
    def transaction(self, mode: str = "IMMEDIATE") -> Iterator[sqlite3.Connection]:
        """One transaction, or the caller's open one. Rolled back if the block raises."""
        if mode not in _MODES:
            raise ValueError(f"mode must be one of {', '.join(_MODES)}")
        with self._lock:
            if self.conn.in_transaction:
                yield self.conn
                return
            self.conn.execute(f"BEGIN {mode}")
            try:
                yield self.conn
            except BaseException:
                if self.conn.in_transaction:
                    self.conn.execute("ROLLBACK")
                raise
            self.conn.execute("COMMIT")

    # -- reading ------------------------------------------------------------------------------------------------

    def get(self, message_id: str) -> Message | None:
        r = self.conn.execute(f"SELECT * FROM {self.table} WHERE message_id = ?", (message_id,)).fetchone()
        return _row(r) if r else None

    def list_ready(self, limit: int | None = None) -> list[Message]:
        sql = f"SELECT * FROM {self.table} WHERE status = 0 ORDER BY ready_at, rowid"
        rows = self.conn.execute(sql + (" LIMIT ?" if limit is not None else ""), (limit,) if limit is not None else ())
        return [_row(r) for r in rows]

    def list_locked(self, older_than_s: float | None = None) -> list[Message]:
        cutoff = self.clock() - _seconds(older_than_s or 0, "older_than_s")
        rows = self.conn.execute(
            f"SELECT * FROM {self.table} WHERE status = 1 AND lock_time <= ? ORDER BY lock_time, rowid", (cutoff,)
        )
        return [_row(r) for r in rows]

    def qsize(self) -> int:
        return self.conn.execute(f"SELECT COUNT(*) FROM {self.table} WHERE status = 0").fetchone()[0]

    def empty(self) -> bool:
        return self.qsize() == 0

    # -- writing ------------------------------------------------------------------------------------------------

    def put(
        self,
        data: str,
        *,
        idempotency_key: str | None = None,
        ready_at: int | None = None,
        delay_s: float = 0,
    ) -> Message:
        if not isinstance(data, str):
            raise TypeError("data must be a string")
        if idempotency_key is not None and not isinstance(idempotency_key, str):
            raise TypeError("idempotency_key must be a string or None")
        with self.transaction():
            if idempotency_key is not None:
                r = self.conn.execute(
                    f"SELECT * FROM {self.table} WHERE idempotency_key = ?", (idempotency_key,)
                ).fetchone()
                if r is not None:
                    if r["data"] != data:
                        raise IdempotencyConflict(f"idempotency key {idempotency_key!r} already holds other data")
                    return _row(r)
            if self.maxsize is not None and self.qsize() >= self.maxsize:
                raise QueueFull(f"the queue already holds {self.maxsize} ready messages")
            now = self.clock()
            when = now + _seconds(delay_s, "delay_s") if ready_at is None else ready_at
            message_id = uuid.uuid4().hex
            self.conn.execute(
                f"INSERT INTO {self.table} (message_id, data, status, in_time, ready_at, idempotency_key) "
                "VALUES (?, ?, 0, ?, ?, ?)",
                (message_id, data, now, when, idempotency_key),
            )
            return _row(self.conn.execute(f"SELECT * FROM {self.table} WHERE message_id = ?", (message_id,)).fetchone())

    def pop(self) -> Message | None:
        with self.transaction():
            now = self.clock()
            r = self.conn.execute(
                f"SELECT message_id FROM {self.table} WHERE status = 0 AND ready_at <= ? ORDER BY ready_at, rowid LIMIT 1",
                (now,),
            ).fetchone()
            if r is None:
                return None
            self.conn.execute(
                f"UPDATE {self.table} SET status = 1, lock_time = ?, claim_id = claim_id + 1 "
                "WHERE message_id = ? AND status = 0",
                (now, r["message_id"]),
            )
            return self.get(r["message_id"])

    def _finish(self, message_id: str, claim_id: int, sets: str, args: tuple) -> Message:
        if isinstance(claim_id, bool) or not isinstance(claim_id, int) or claim_id < 1:
            raise StaleClaim("claim_id must be a whole number of 1 or more")
        with self.transaction():
            cur = self.conn.execute(
                f"UPDATE {self.table} SET {sets} WHERE message_id = ? AND status = 1 AND claim_id = ?",
                (*args, message_id, claim_id),
            )
            if cur.rowcount != 1:
                raise StaleClaim(f"{message_id} is not locked at claim {claim_id}")
            return self.get(message_id)  # type: ignore[return-value]

    def done(self, message_id: str, claim_id: int) -> Message:
        return self._finish(message_id, claim_id, "status = 2, done_time = ?", (self.clock(),))

    def mark_failed(self, message_id: str, claim_id: int) -> Message:
        return self._finish(message_id, claim_id, "status = 3, done_time = ?", (self.clock(),))

    def retry(self, message_id: str, claim_id: int, delay_s: float = 0, count_try: bool = True) -> Message:
        now = self.clock()
        return self._finish(
            message_id,
            claim_id,
            "status = 0, lock_time = NULL, ready_at = ?, tries = tries + ?",
            (now + _seconds(delay_s, "delay_s"), 1 if count_try else 0),
        )

    def heartbeat(self, message_id: str, claim_id: int) -> Message:
        return self._finish(message_id, claim_id, "lock_time = ?", (self.clock(),))

    def retry_expired(self, lease_s: float, count_try: bool = False) -> int:
        with self.transaction():
            now = self.clock()
            cur = self.conn.execute(
                f"UPDATE {self.table} SET status = 0, lock_time = NULL, ready_at = ?, tries = tries + ? "
                "WHERE status = 1 AND lock_time <= ?",
                (now, 1 if count_try else 0, now - _seconds(lease_s, "lease_s")),
            )
            return cur.rowcount

    def discard(self, message_id: str) -> bool:
        with self.transaction():
            return (
                self.conn.execute(
                    f"DELETE FROM {self.table} WHERE message_id = ? AND status = 0", (message_id,)
                ).rowcount
                == 1
            )

    def prune(self, older_than_s: float, statuses: tuple[Status, ...] = (Status.DONE, Status.FAILED)) -> int:
        marks = ", ".join("?" for _ in statuses)
        with self.transaction():
            cutoff = self.clock() - _seconds(older_than_s, "older_than_s")
            return self.conn.execute(
                f"DELETE FROM {self.table} WHERE status IN ({marks}) AND done_time <= ?",
                (*[int(s) for s in statuses], cutoff),
            ).rowcount

    def close(self) -> None:
        if self._owns:
            self.conn.close()
